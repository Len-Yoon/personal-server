"""Freeze synthetic legacy sources and migrate them into the isolated PG lab.

Every source is generated by the real application's legacy implementation.
No production paths, provider calls, credentials or business values are printed.
"""
import argparse
from datetime import date, datetime, timedelta, timezone
import hashlib
import json
import os
from pathlib import Path
import sqlite3
import sys

SERVICES = ("crawler-worker", "car-care-worker", "homeops-executor", "system-agent")


def configure(service):
    os.environ.pop("HA_PG_CONFIG", None)
    root = Path("/tmp/ha-seed") / service
    root.mkdir(parents=True, exist_ok=True)
    paths = {
        "DATA_ROOT": root,
        "NEWS_ARCHIVE_PATH": root / "news_archive.json",
        "NEWS_COLLECTION_STATUS_PATH": root / "news_collection_status.json",
        "CAR_CARE_DB_PATH": root / "car-care.sqlite3",
        "HYUNDAI_TOKEN_STORE_PATH": root / "hyundai-token.json",
        "HOMEOPS_IDEMPOTENCY_DB_PATH": root / "restarts.sqlite3",
    }
    os.environ.update({name: str(path) for name, path in paths.items()})
    source = Path(os.getenv("HA_APP_SOURCE", "/source"))
    sys.path.insert(0, str(source / "infra/k8s"))
    sys.path.insert(0, str(source / service))
    return root


