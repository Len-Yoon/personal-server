"""Export one isolated, restored PostgreSQL component to its legacy SQLite format.

The frozen SQLite backup supplies schema, indexes and historic identity bounds.
The restored PostgreSQL snapshot supplies all application rows. This does not
convert JSON state, external effects or files, and does not activate either app.
"""
from contextlib import closing
import hashlib
import json
import math
import os
from pathlib import Path
import re
import sqlite3
import stat
import tempfile
import uuid

from . import migrate
from .config import schema_name
from .seven_migration import DATABASES, need, private_file, read_verified


BOOKKEEPING_TABLES = {'ha_receipts', 'ha_barriers'}
ISOLATED_CLUSTER = re.compile(r'ha_legacy_export_[a-f0-9]{32}\Z')
IDENTIFIER = re.compile(r'[a-z_][a-z0-9_]*\Z')
FROZEN_SIDECARS = ('-wal', '-shm', '-journal')


def _private_directory(path):
    need(path.is_absolute() and '..' not in path.parts, 'legacy_export_private_directory_required')
    info = path.lstat()
    need(stat.S_ISDIR(info.st_mode) and info.st_uid == os.geteuid() and not info.st_mode & 0o077,
         'legacy_export_private_directory_required')
    for parent in path.parents:
        info = parent.lstat()
        sticky_root = info.st_uid == 0 and bool(info.st_mode & stat.S_ISVTX)
        need(stat.S_ISDIR(info.st_mode) and info.st_uid in {0, os.geteuid()}
             and (not info.st_mode & 0o022 or sticky_root), 'legacy_export_private_directory_required')


def _has_sidecar(path):
    return any(os.path.lexists(str(path) + suffix) for suffix in FROZEN_SIDECARS)


def _template_definition(source):
    source.execute('PRAGMA trusted_schema=OFF')
    need(source.execute('PRAGMA quick_check').fetchall() == [('ok',)]
         and source.execute('PRAGMA foreign_key_check').fetchone() is None,
         'legacy_export_invalid_template')
    need(source.execute("SELECT 1 FROM sqlite_master WHERE type NOT IN ('table','index')").fetchone() is None,
         'legacy_export_unsupported_template')
    tables = {}
    for name, ddl in migrate._source_tables(source).items():
        translated = migrate._ddl(ddl)
        column_info = source.execute(f'PRAGMA table_info("{name}")').fetchall()
        columns = [row[1] for row in column_info]
        integer_pk = [row[1] for row in column_info if row[2].upper() == 'INTEGER' and row[5]]
        identity = integer_pk if 'BIGINT GENERATED BY DEFAULT AS IDENTITY' in translated else []
        unquoted = ''.join(re.split(r"('(?:''|[^'])*')", ddl)[::2])
        auto = re.search(r'\bAUTOINCREMENT\b', unquoted, re.I) is not None
        need(columns and all(IDENTIFIER.fullmatch(col) for col in columns)
             and len(identity) <= 1 and (not auto or bool(identity)), 'legacy_export_unsupported_template')
        tables[name] = (ddl, columns, identity, auto)
    need(tables and not BOOKKEEPING_TABLES.intersection(tables), 'legacy_export_invalid_template')
    indexes = source.execute("SELECT name,sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL").fetchall()
    for name, ddl in indexes:
        need(IDENTIFIER.fullmatch(name) and re.match(r'CREATE\s+(?:UNIQUE\s+)?INDEX\s', ddl, re.I),
             'legacy_export_unsupported_template')
        migrate._safe_source_sql(ddl)
    old_bounds = {}
    if source.execute("SELECT 1 FROM sqlite_master WHERE name='sqlite_sequence'").fetchone():
        for name, bound in source.execute('SELECT name,seq FROM sqlite_sequence'):
            need(name in tables and tables[name][3] and name not in old_bounds
                 and type(bound) is int and bound >= 0, 'legacy_export_template_sequence_unconfirmed')
            old_bounds[name] = bound
    return tables, indexes, old_bounds


def _check_catalog(connection, schema, tables):
    rows = connection.execute("""SELECT c.relname,c.relkind FROM pg_catalog.pg_class c
        JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname=%s AND c.relkind IN ('r','p','v','m','f')""", (schema,)).fetchall()
    names = {name for name, _ in rows}
    need(all(kind == 'r' for _, kind in rows) and names == set(tables) | BOOKKEEPING_TABLES,
         'legacy_export_postgres_tables_mismatch')
    for name, (_, columns, identity, _) in tables.items():
        info = connection.execute("""SELECT column_name,is_identity FROM information_schema.columns
            WHERE table_schema=%s AND table_name=%s ORDER BY ordinal_position""", (schema, name)).fetchall()
        need([column for column, _ in info] == columns
             and all(flag in {'YES', 'NO'} for _, flag in info)
             and [column for column, flag in info if flag == 'YES'] == identity,
             'legacy_export_postgres_columns_mismatch')


def _sequence(connection, schema, table, column):
    from psycopg import sql
    sequence = connection.execute("""SELECT n.nspname,c.relname,s.seqstart,s.seqincrement,s.seqmin,s.seqcycle,s.seqcache
        FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
        JOIN pg_catalog.pg_sequence s ON s.seqrelid=c.oid
        WHERE c.oid=pg_catalog.pg_get_serial_sequence(%s,%s)::regclass AND c.relkind='S'""",
        (sql.Identifier(schema, table).as_string(), column)).fetchone()
    need(sequence is not None and sequence[0] == schema and IDENTIFIER.fullmatch(sequence[1])
         and sequence[2:] == (1, 1, 1, False, 1), 'legacy_export_sequence_unconfirmed')
    row = connection.execute(sql.SQL('SELECT last_value,is_called FROM {}').format(
        sql.Identifier(schema, sequence[1]))).fetchone()
    need(row is not None and type(row[0]) is int and row[0] > 0 and type(row[1]) is bool
         and (row[1] or row[0] == 1), 'legacy_export_sequence_unconfirmed')
    return row[0] if row[1] else 0


def _value(value):
    # SQLite affinity can still coerce valid values. The destination readback
    # compares a typed digest independently and rejects all such changes.
    if isinstance(value, memoryview):
        return bytes(value)
    if type(value) is int:
        need(-(2**63) <= value < 2**63, 'legacy_export_value_unrepresentable')
    elif type(value) is float:
        need(math.isfinite(value), 'legacy_export_value_unrepresentable')
    else:
        need(value is None or type(value) in {str, bytes}, 'legacy_export_value_unrepresentable')
    return value


def _row_hash(row):
    typed = []
    for value in row:
        tag = type(value).__name__
        if type(value) is bytes:
            value = value.hex()
        elif type(value) is float:
            value = value.hex()
        typed.append((tag, value))
    return hashlib.sha256(json.dumps(typed, ensure_ascii=False, allow_nan=False,
                                     separators=(',', ':')).encode()).digest()


def _compare(hashes):
    source = hashes.execute('SELECT digest FROM row_hashes WHERE side=0 ORDER BY digest')
    target = hashes.execute('SELECT digest FROM row_hashes WHERE side=1 ORDER BY digest')
    result = hashlib.sha256()
    count = 0
    while True:
        rows = source.fetchmany(256)
        need(rows == target.fetchmany(256), 'legacy_export_value_readback_mismatch')
        if not rows:
            break
        for (digest,) in rows:
            result.update(digest)
        count += len(rows)
    return {'rows': count, 'sha256': result.hexdigest()}


def _table(connection, target, hashes, schema, table, definition, historic):
    from psycopg import sql
    _, columns, identity, auto = definition
    select = sql.SQL('SELECT {} FROM {}').format(
        sql.SQL(',').join(map(sql.Identifier, columns)), sql.Identifier(schema, table))
    sqlite_columns = ','.join(f'"{column}"' for column in columns)
    placeholders = ','.join('?' for _ in columns)
    insert = f'INSERT INTO "{table}" ({sqlite_columns}) VALUES ({placeholders})'
    high_water = _sequence(connection, schema, table, identity[0]) if identity else None
    hashes.execute('DELETE FROM row_hashes')
    with connection.cursor(name='legacy_export_' + uuid.uuid4().hex) as source:
        source.execute(select)
        while rows := source.fetchmany(256):
            typed = [tuple(map(_value, row)) for row in rows]
            target.executemany(insert, typed)
            hashes.executemany('INSERT INTO row_hashes VALUES(0,?)', [(_row_hash(row),) for row in typed])
    cursor = target.execute(f'SELECT {sqlite_columns} FROM "{table}"')
    while rows := cursor.fetchmany(256):
        hashes.executemany('INSERT INTO row_hashes VALUES(1,?)', [(_row_hash(row),) for row in rows])
    result = _compare(hashes)
    if identity:
        need(_sequence(connection, schema, table, identity[0]) == high_water, 'legacy_export_source_sequence_changed')
        maximum = max(0, target.execute(f'SELECT max("{identity[0]}") FROM "{table}"').fetchone()[0] or 0)
        bound = max(high_water, maximum, historic)
        if auto:
            target.execute('DELETE FROM sqlite_sequence WHERE name=?', (table,))
            target.execute('INSERT INTO sqlite_sequence(name,seq) VALUES(?,?)', (table, bound))
            need(target.execute('SELECT seq FROM sqlite_sequence WHERE name=?', (table,)).fetchall() == [(bound,)],
                 'legacy_export_target_sequence_unconfirmed')
        else:
            need(bound == maximum, 'legacy_export_rowid_high_water_unrepresentable')
        result['identity_high_water'] = bound
    return result


def _fingerprint(path):
    with path.open('rb') as handle:
        return hashlib.file_digest(handle, 'sha256').hexdigest()


def export_component(connection, *, expected_cluster, service, component, template, template_sha256, output):
    """Publish a new SQLite artifact and metadata after exact isolated readback.

    The caller supplies an idle autocommit psycopg connection to database
    `ha` on a separately restored instance named `ha_legacy_export_<32 hex>`.
    Export captures one component at a time; keep that restored source inert
    until every component and its companion state has been converted.
    """
    from psycopg.pq import TransactionStatus

    need(isinstance(expected_cluster, str) and ISOLATED_CLUSTER.fullmatch(expected_cluster)
         and isinstance(service, str) and isinstance(component, str)
         and component in DATABASES.get(service, set())
         and connection.autocommit is True and connection.info.transaction_status == TransactionStatus.IDLE,
         'legacy_export_isolated_source_required')
    schema = schema_name(service, component)
    template = private_file(template)
    output = Path(output)
    _private_directory(output.parent)
    need(not os.path.lexists(output) and not _has_sidecar(output) and not _has_sidecar(template),
         'legacy_export_frozen_inputs_and_new_output_required')
    with tempfile.TemporaryDirectory(prefix='.legacy-sqlite-export-', dir=output.parent) as folder:
        stage = Path(folder)
        frozen = stage / 'template.sqlite3'
        with frozen.open('xb') as sink:
            read_verified(template, template_sha256, template.stat().st_size, load=False, sink=sink)
        need(not _has_sidecar(template), 'legacy_export_frozen_inputs_and_new_output_required')
        with closing(sqlite3.connect(frozen.as_uri() + '?mode=ro&immutable=1', uri=True)) as source:
            tables, indexes, old_bounds = _template_definition(source)

        candidate = stage / 'output.sqlite3'
        candidate.touch(mode=0o600, exist_ok=False)
        with (connection.transaction(), closing(sqlite3.connect(candidate)) as target,
              closing(sqlite3.connect(stage / 'hashes.sqlite3')) as hashes):
            connection.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY')
            need(connection.execute("SELECT current_database(),current_setting('cluster_name'),current_setting('transaction_read_only')"
                                    ).fetchone() == ('ha', expected_cluster, 'on'),
                 'legacy_export_isolated_source_required')
            _check_catalog(connection, schema, tables)
            hashes.execute('CREATE TABLE row_hashes(side INTEGER,digest BLOB)')
            hashes.execute('CREATE INDEX row_hash_order ON row_hashes(side,digest)')
            target.execute('PRAGMA trusted_schema=OFF')
            target.execute('PRAGMA foreign_keys=ON')
            target.execute('BEGIN')
            target.execute('PRAGMA defer_foreign_keys=ON')
            for ddl, _, _, _ in tables.values():
                target.execute(ddl)
            results = {table: _table(connection, target, hashes, schema, table, definition, old_bounds.get(table, 0))
                       for table, definition in tables.items()}
            for _, ddl in indexes:
                target.execute(ddl)
            need(target.execute('PRAGMA foreign_key_check').fetchone() is None, 'legacy_export_foreign_key_readback_mismatch')
            target.commit()
            need(target.execute('PRAGMA quick_check').fetchall() == [('ok',)], 'legacy_export_sqlite_readback_mismatch')
        need(not _has_sidecar(candidate), 'legacy_export_sqlite_readback_mismatch')
        with candidate.open('rb') as handle:
            os.fsync(handle.fileno())
        fingerprint = _fingerprint(candidate)
        parent = os.open(output.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try:
            os.link(candidate, output.name, dst_dir_fd=parent, follow_symlinks=False)
            os.fsync(parent)
        finally:
            os.close(parent)
        return {'service': service, 'component': component, 'artifact_sha256': fingerprint, 'tables': results}
