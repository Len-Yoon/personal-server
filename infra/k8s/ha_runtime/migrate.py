"""Frozen, isolated-source migrations with complete logical comparison.

Not an online cutover command. Production data/credentials and Windows are not
accepted here. A future operator procedure must first quiesce ALL old writers.
"""
import json
from pathlib import Path
import re
import sqlite3

from .config import DatabaseUnavailable, schema_name
from .proof import digest


def create_namespace(admin, service, component="main"):
    from psycopg import sql
    schema = schema_name(service, component)
    admin.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
    admin.execute(sql.SQL("REVOKE ALL ON SCHEMA {} FROM PUBLIC").format(sql.Identifier(schema)))
    admin.execute(sql.SQL("SET search_path TO {},pg_catalog").format(sql.Identifier(schema)))
    admin.execute("CREATE TABLE ha_receipts(receipt text PRIMARY KEY,payload_hash text NOT NULL,result_hash text NOT NULL)")
    admin.execute("CREATE TABLE ha_barriers(attempt text PRIMARY KEY,receipt text NOT NULL REFERENCES ha_receipts(receipt),epoch bigint NOT NULL)")
    if component == "state":
        admin.execute("CREATE TABLE shared_state(key text PRIMARY KEY,payload jsonb NOT NULL,version bigint NOT NULL)")
        if service == "portal-web":
            from .blobs import setup_namespace
            setup_namespace(admin, schema)
    return schema


def grant_namespace(admin, schema, roles, *, enforced_service=None, enforced_generation=None):
    from psycopg import sql
    if enforced_service is not None:
        # Never publish DML privileges before the closed-authority installation.
        from .enforcement import install_namespace
        return install_namespace(admin, schema, enforced_service, roles, generation=enforced_generation)
    for role in roles:
        admin.execute(sql.SQL("GRANT USAGE ON SCHEMA {} TO {}").format(sql.Identifier(schema), sql.Identifier(role)))
        for table in admin.execute("SELECT tablename FROM pg_tables WHERE schemaname=%s", (schema,)).fetchall():
            name = table[0]
            permissions = "SELECT,INSERT" if name in {"ha_receipts", "ha_barriers", "ha_blob_objects", "ha_blob_chunks"} else "SELECT,INSERT,UPDATE,DELETE"
            admin.execute(sql.SQL("GRANT " + permissions + " ON {}.{} TO {}").format(sql.Identifier(schema), sql.Identifier(name), sql.Identifier(role)))
        admin.execute(sql.SQL("GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA {} TO {}").format(sql.Identifier(schema), sql.Identifier(role)))


def _safe_source_sql(source):
    """Legacy files supply data, never administrator-executed arbitrary SQL."""
    if not isinstance(source,str) or ';' in source or '\x00' in source:
        raise DatabaseUnavailable('unsupported_source_schema')
    code=''.join(re.split(r"('(?:''|[^'])*')",source)[::2])
    code=re.sub(r'"([A-Za-z_][A-Za-z0-9_]*)"',r'\1',code)
    if ('--' in code or '/*' in code or re.search(r'\b[A-Za-z_][A-Za-z0-9_]*\s*\.',code)
            or re.search(r'\b(GENERATED|VIRTUAL|STRICT)\b|\bWITHOUT\s+ROWID\b|\bAS\s+SELECT\b',code,re.I)):
        raise DatabaseUnavailable('unsupported_source_schema')
    pure={'CHECK','IN','KEY','UNIQUE','CAST','VARCHAR','CHAR','NUMERIC','DECIMAL',
          'LENGTH','LOWER','UPPER','ABS','COALESCE','NULLIF','TRIM','LTRIM','RTRIM','ROUND'}
    for match in re.finditer(r'([A-Za-z_][A-Za-z0-9_]*)\s*\(',code):
        prefix=code[:match.start()].rstrip()
        declaration=re.search(r'\b(CREATE\s+TABLE(?:\s+IF\s+NOT\s+EXISTS)?|REFERENCES|ON)\s*$',prefix,re.I)
        if match[1].upper() not in pure and declaration is None:
            raise DatabaseUnavailable('executable_source_schema_rejected')


def _ddl(source):
    # Only this repository's table DDL. No virtual tables, triggers, user-defined
    # functions or executable default expressions are imported from outside SQL.
    if not re.match(r"CREATE TABLE\b", source, re.I) or ";" in source:
        raise DatabaseUnavailable("unsupported_source_schema")
    _safe_source_sql(source)
    parts = re.split(r"('(?:''|[^'])*')", source)
    for index in range(0, len(parts), 2):
        value = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY(?:\s+AUTOINCREMENT)?\b",
                       "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", parts[index], flags=re.I)
        value = re.sub(r"\bINTEGER\b", "BIGINT", value, flags=re.I)
        value = re.sub(r"\bREAL\b", "DOUBLE PRECISION", value, flags=re.I)
        value = re.sub(r"\bBLOB\b", "BYTEA", value, flags=re.I)
        parts[index] = re.sub(r"\bDEFAULT\s+CURRENT_TIMESTAMP\b",
                       "DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))", value, flags=re.I)
    return "".join(parts)


def _source_tables(source):
    tables=dict(source.execute("SELECT name,sql FROM sqlite_master WHERE type='table' AND substr(name,1,7)<>'sqlite_'"))
    if any(not re.fullmatch(r'[a-z_][a-z0-9_]*',name) for name in tables):
        raise DatabaseUnavailable('unsupported_source_table')
    return tables


def copy_sqlite(admin, service, component, source_path):
    """Preserve IDs, values, relationships, indexes and deleted-ID high watermarks."""
    source_path = Path(source_path)
    if not source_path.is_absolute() or source_path.is_symlink() or not source_path.is_file():
        raise DatabaseUnavailable("frozen_source_required")
    if any(Path(str(source_path)+suffix).exists() and Path(str(source_path)+suffix).stat().st_size
           for suffix in ('-wal','-journal')):
        raise DatabaseUnavailable('frozen_sqlite_backup_required')
    reader = sqlite3.connect(source_path.as_uri() + "?mode=ro&immutable=1", uri=True)
    source = sqlite3.connect(":memory:")
    try:
        reader.backup(source)
        if source.execute("PRAGMA quick_check").fetchall() != [("ok",)] or source.execute("PRAGMA foreign_key_check").fetchall():
            raise DatabaseUnavailable("source_integrity_failed")
        if source.execute("SELECT 1 FROM sqlite_master WHERE type IN ('trigger','view') LIMIT 1").fetchone():
            raise DatabaseUnavailable('unsupported_source_objects')
        tables = _source_tables(source)
        if any(not re.fullmatch(r"[a-z_][a-z0-9_]*", name) for name in tables):
            raise DatabaseUnavailable("unsupported_source_table")
        dependencies = {name: {row[2] for row in source.execute('PRAGMA foreign_key_list("' + name + '")') if row[2] != name}
                        for name in tables}
        order = []
        while len(order) < len(tables):
            ready = sorted(name for name in tables if name not in order and dependencies[name] <= set(order))
            if not ready:
                raise DatabaseUnavailable("unsupported_foreign_key_cycle")
            order.extend(ready)
        translated={name:_ddl(ddl) for name,ddl in tables.items()}
        indices=list(source.execute("SELECT name,sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL"))
        for name,ddl in indices:
            if not re.fullmatch(r'[a-z_][a-z0-9_]*',name):
                raise DatabaseUnavailable('unsupported_source_index')
            _safe_source_sql(ddl)
        from psycopg import sql
        schema = create_namespace(admin, service, component)
        manifests = {}
        for table in order:
            admin.execute(translated[table])
            columns = [row[1] for row in source.execute('PRAGMA table_info("' + table + '")')]
            rows = source.execute('SELECT * FROM "' + table + '"').fetchall()
            statement = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
                sql.Identifier(table), sql.SQL(",").join(map(sql.Identifier, columns)),
                sql.SQL(",").join(sql.Placeholder() for _ in columns),
            )
            with admin.cursor() as cursor:
                cursor.executemany(statement, rows)
            restored = admin.execute(sql.SQL("SELECT {} FROM {}").format(sql.SQL(",").join(map(sql.Identifier, columns)), sql.Identifier(table))).fetchall()
            logical = lambda values: sorted(digest(list(row)) for row in values)
            if logical(rows) != logical(restored):
                raise DatabaseUnavailable("logical_migration_mismatch")
            identities = admin.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=%s AND table_name=%s AND is_identity='YES'", (schema, table)).fetchall()
            for identity in identities:
                column = identity[0]
                maximum = admin.execute(sql.SQL("SELECT max({}) FROM {}").format(sql.Identifier(column), sql.Identifier(table))).fetchone()[0] or 0
                if "sqlite_sequence" in {r[0] for r in source.execute("SELECT name FROM sqlite_master WHERE type='table'")}:
                    old = source.execute("SELECT seq FROM sqlite_sequence WHERE name=?", (table,)).fetchone()
                    maximum = max(maximum, old[0] if old else 0)
                admin.execute("SELECT setval(pg_get_serial_sequence(%s,%s),%s,%s)", (schema + "." + table, column, max(1, maximum), maximum > 0))
            manifests[table] = {"rows": len(rows), "sha256": digest(logical(rows)), "columns": columns}
        for name, ddl in indices:
            if ";" in ddl or not re.fullmatch(r"[a-z_][a-z0-9_]*", name):
                raise DatabaseUnavailable("unsupported_source_index")
            # PostgreSQL requires parentheses around CASE index expressions.
            ddl = re.sub(r"\bCASE\b(.*?)\bEND\b", lambda match: "(" + match[0] + ")", ddl, flags=re.I | re.S)
            admin.execute(ddl)
        return {"service": service, "component": component, "tables": manifests}
    finally:
        source.close()
        reader.close()


def seed_state(admin, service, key, payload):
    from psycopg import sql
    from psycopg.types.json import Jsonb
    schema = schema_name(service, "state")
    admin.execute(sql.SQL("INSERT INTO {}.shared_state(key,payload,version) VALUES(%s,%s,1)").format(sql.Identifier(schema)), (key, Jsonb(payload)))


def read_json_source(path):
    # Missing/unreadable/corrupt source is not silently replaced by empty state.
    target = Path(path)
    if not target.is_absolute() or target.is_symlink():
        raise DatabaseUnavailable("invalid_json_migration_source")
    return json.loads(target.read_text(encoding="utf-8"))
